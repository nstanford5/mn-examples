// This file's main purpose is to export the compiled contract. The imports below
// resolve against contract/managed/election, which is generated by `yarn compile`
// (gitignored). Write contract/election.compact first, then compile.
import { CompiledContract } from '@midnight-ntwrk/midnight-js-protocol/compact-js';
import path from 'node:path';

export {
  Contract,
  ledger,
  pureCircuits,
  type Witnesses,
  type Ledger,
  type ImpureCircuits,
  type PureCircuits,
} from './managed/election/contract/index.js';
import { Contract } from './managed/election/contract/index.js';
import { witnesses } from './witnesses.js';
const currentDir = path.resolve(new URL(import.meta.url).pathname, '..');
export const zkConfigPath = path.resolve(currentDir, 'managed', 'election');

export const CompiledElectionContract = CompiledContract.make(
  'ElectionContract',
  Contract,
).pipe(
  // This contract declares witnesses (localSk / localGetVote), so wire in their
  // implementations rather than the vacant (no-op) witness set.
  CompiledContract.withWitnesses(witnesses),
  CompiledContract.withCompiledFileAssets(zkConfigPath),
);
